  @spec data() :: [map()]
  def data, do: Enum.map(@needles, &to_attrs/1)

  @spec seed() :: :ok
  def seed do
    Enum.each(data(), fn attrs ->
      %Catalog.Needle{}
      |> Catalog.Needle.changeset(attrs)
      |> Repo.insert!(
        on_conflict: {:replace_all_except, [:id, :inserted_at]},
        conflict_target: :part_number
      )
    end)
  end

  defp to_attrs({series, code, _taper_deg, _l1_mm, _root_mm} = entry) do
    geom = geometry(entry)

    %{
      part_number: "#{series}-#{code}",
      manufacturer: "keihin",
      series: series,
      total_length_tenths_mm: round(geom.total_mm * 10),
      taper_points_tenths_mm: [round(geom.l1_mm * 10)],
      station_diameters_um: sample_diameters_um(geom),
      num_clips: @family_num_clips[series]
    }
  end

  defp sample_diameters_um(geometry) do
    step_mm = (geometry.total_mm - geometry.l1_mm) / (@stations - 1)

    Enum.map(0..(@stations - 1), fn i ->
      position_mm = geometry.l1_mm + i * step_mm
      round(diameter_at(position_mm, geometry) * 1000)
    end)
  end

  defp diameter_at(position_mm, %{knee_mm: knee} = g) when position_mm <= knee do
    g.root_mm - (position_mm - g.l1_mm) * g.main_rate
  end

  defp diameter_at(position_mm, g) do
    max(@reference_mm - (position_mm - g.knee_mm) * g.tip_rate, @tip_mm)
  end

  defp geometry({series, _code, taper_deg, l1_mm, root_mm}) do
    total_mm = @family_total_length_mm[series]
    main_rate = 2 * :math.tan(taper_deg * :math.pi() / 180 / 2)
    knee_mm = l1_mm + (root_mm - @reference_mm) / main_rate
    tip_rate = (@reference_mm - @tip_mm) / (total_mm - knee_mm)

    %{
      l1_mm: l1_mm,
      root_mm: root_mm,
      total_mm: total_mm,
      knee_mm: knee_mm,
      main_rate: main_rate,
      tip_rate: tip_rate
    }
  end
